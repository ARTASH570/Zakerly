/**
 * تحويل السعر من الجنيه المصري (العملة الأساسية اللي بيتسعّر بيها كل كورس)
 * لسنتات الدولار - مطلوب لأن Stripe وPayPal بياخدوا الدفع بالدولار بس،
 * على عكس Paymob اللي بياخد جنيه مباشرة (`currency: 'EGP'` في paymob.ts).
 *
 * ⚠️ قبل الإصلاح ده، كان الكود بيبعت السعر بالجنيه لـ Stripe/PayPal 1:1
 * وكأنه دولار - يعني كورس بـ 500 جنيه كان بيتحصّل كـ 500 دولار فعليًا.
 *
 * ده سعر صرف ثابت (بتحطه إنت يدويًا في متغير بيئة) مش سعر صرف حي من API -
 * كفاية للمشروع دلوقتي، بس لازم تحدّثه بنفسك من وقت للتاني حسب سعر الصرف
 * الفعلي. لو حابب تحويل حي أوتوماتيكي، استبدل الدالة دي باستدعاء API
 * سعر صرف خارجي (مع كاش قصير المدة عشان منكلمش الـ API في كل عملية دفع).
 */
export function egpToUsdCents(amountEgp: number): number {
  const rate = Number(process.env.EGP_TO_USD_RATE)

  if (!rate || rate <= 0 || Number.isNaN(rate)) {
    throw new Error(
      'متغير البيئة EGP_TO_USD_RATE مش متظبط أو غير صحيح - لازم يكون رقم أكبر من صفر (مثلاً 0.021 لو الدولار بـ ~47 جنيه). ' +
        'من غير المتغير ده، الدفع بالدولار (Stripe/PayPal) هيفضل موقوف عشان منحصلش الطلاب بسعر غلط.'
    )
  }

  const usd = amountEgp * rate
  return Math.round(usd * 100)
}
